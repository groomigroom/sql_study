문제 14

4지선다
다음 SQL의 수행 결과로 옳은 것은?

SQL
SELECT REGEXP_COUNT('abcdabcdabcdabcd', 'ab', 1)
FROM DUAL;
1.
2

2.
3

3.
4

4.
5

정답

3번

4

해설

정답은 ③ 4이다. REGEXP_COUNT는 지정한 시작 위치부터 문자열 전체를 검색하여 정규 표현식과 일치하는 횟수를 반환한다. 문자열 abcd가 네 번 반복되고 각 반복마다 ab가 한 번씩 나타나므로 일치 횟수는 4회다. 세 번째 인수 1은 첫 번째 문자부터 검색한다는 뜻이며 첫 번째 발생 위치만 반환하는 값이 아니다. ① 2와 ② 3은 일부 반복을 누락한 결과이고, ④ 5는 실제 존재하는 ab의 수보다 하나 많다. 또한 일치 항목은 서로 겹치지 않으며 이 문자열에서는 경계에 걸친 추가 일치도 생기지 않는다. 보충: REGEXP_COUNT의 세 번째 인수는 검색 시작 위치이고 반환값은 일치한 부분 문자열의 개수다.
